#!/usr/bin/env node
// Produce a ready-to-paste Serverless function with the real, local config
// inlined.
//
// Why this exists: plugins/blackboard-week/serverless.js is committed to a
// public repo, so it ships a synthetic example SEMESTER block. The real class
// schedule lives in local/semester.local.js, which is gitignored. Swapping the
// block by hand before pasting into TRMNL is a step that is easy to skip — and
// skipping it silently deploys placeholder course names ("MGT 0000",
// "Analytics") that look like real data. This does the swap mechanically and
// fails loudly if anything is off.
//
//   node tools/build-serverless.mjs blackboard-week
//
// Output goes to plugins/<name>/local/serverless.deploy.js, which is gitignored.

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const SEMESTER_RE = /var SEMESTER = \{[\s\S]*?\n\};\n/;

const plugin = process.argv[2];
if (!plugin) {
  console.error('usage: node tools/build-serverless.mjs <plugin-name>');
  process.exit(2);
}

const dir = join(REPO_ROOT, 'plugins', plugin);
const srcPath = join(dir, 'serverless.js');
const cfgPath = join(dir, 'local', 'semester.local.js');
const outPath = join(dir, 'local', 'serverless.deploy.js');

for (const [label, p] of [['serverless.js', srcPath], ['local/semester.local.js', cfgPath]]) {
  if (!existsSync(p)) {
    console.error(`missing ${label} at ${p}`);
    process.exit(1);
  }
}

const src = await readFile(srcPath, 'utf8');
const cfgFile = await readFile(cfgPath, 'utf8');

const cfgMatch = SEMESTER_RE.exec(cfgFile);
if (!cfgMatch) {
  console.error('local/semester.local.js has no "var SEMESTER = { … };" block');
  process.exit(1);
}
if (!SEMESTER_RE.test(src)) {
  console.error('serverless.js has no "var SEMESTER = { … };" block to replace');
  process.exit(1);
}

const merged = src.replace(SEMESTER_RE, cfgMatch[0]);

// The example block must actually be gone, or the paste is a no-op.
if (merged.includes('MGT 0000') || merged.includes('Team Dynamics')) {
  console.error('example config still present after substitution — check the markers');
  process.exit(1);
}

// This file is what reaches the device, so hold it to the runtime's limits:
// TRMNL's Serverless runtime corrupts multi-byte UTF-8 on the way out.
const nonAscii = [...new Set([...merged].filter((ch) => ch.codePointAt(0) > 127))];
if (nonAscii.length > 0) {
  console.warn(`  note: source contains non-ASCII (${nonAscii.join(' ')}) — asciiDeep() folds the payload, but prefer ASCII in config strings`);
}

const banner = `// GENERATED by tools/build-serverless.mjs — do not edit.
// Source: plugins/${plugin}/serverless.js + local/semester.local.js
// Built:  ${new Date().toISOString()}
//
// Paste THIS file into TRMNL (Markup Editor -> Serverless, Node runtime), not
// the committed serverless.js, which carries a placeholder semester config.

`;

await writeFile(outPath, banner + merged, 'utf8');
console.log(`wrote ${outPath.replace(REPO_ROOT + '/', '')}`);
console.log('  paste this into TRMNL -> Markup Editor -> Serverless (Node)');
